# Generate the embedded assembly: compile the rewritten module image into the executable, with code going into the single executable segment __TEXT only (Apple ITMS-90999: only one segment with execute permission is allowed).
#   __TEXT,__dm<name>x0   original text: [0, round16K(TEXT_END)) (includes part of the first ro page, read-only)
#   __DM<name>W,__img     RW segment: [round16K(TEXT_END), PATCH_OFF), rest of ro + data + bss (relocations land only here)
#   __TEXT,__dm<name>x1   patch area: [PATCH_OFF, round16K(end of file))
# The three pieces are not adjacent in the executable; at run time the loader (loader.c iOS branch) reserves one contiguous address range and vm_remaps them back at their original relative positions (code pages share the signed pages, W is copy-on-write),
# so the run-time layout is byte-identical to the original image: PC-relative addressing between original code and data, relative jumps in the patch area, and the host's "base + original offset" references all need no change.
# Code options (plan item 136): iOS maps the signed executable's code, which the loader cannot change, so the options the app is built with
# (DM_OPTIONS at build time, else the product's options.default; "none" for none) are written here into a copy of the image (<output dir>/<module>
# .embedded.bin), each option's original bytes checked first and all of its rows written or the build stops; the loader reads them back from the
# image (host/options.c dm_options_embedded). A module without one of them is included as the product has it. Checked by tools/tests/t_gen_embed.py.
# Usage: gen_embed.py <build output dir> <output .S> <module name...>; link flags are printed to stdout (-segprot for the W segment)
import os, re, sys
out, dst, names = sys.argv[1], sys.argv[2], sys.argv[3:]
def options_wanted():
    s = os.environ.get('DM_OPTIONS')
    if s is None: s = open(f'{out}/options.default').read() if os.path.exists(f'{out}/options.default') else ''
    return [x for x in re.split(r'[,\s]+', s) if x and x != 'none']
WANTED, seen = options_wanted(), set()
def embedded_image(n):   # the image to include: the product's, or a copy with the options written
    rows = {}
    if os.path.exists(f'{out}/{n}.options.tsv'):
        for l in open(f'{out}/{n}.options.tsv', encoding='utf-8'):
            if l.startswith('#') or not l.strip(): continue
            name, off, ob, nb = l.split('\t')[:4]; seen.add(name); rows.setdefault(name, []).append((int(off, 0), bytes.fromhex(ob), bytes.fromhex(nb)))
    use = [o for o in WANTED if o in rows]
    src = os.path.abspath(f'{out}/{n}.patched.bin')
    if not use: return src
    img = bytearray(open(src, 'rb').read())
    for o in use:   # every row of an option checked before any is written
        for off, ob, nb in rows[o]:
            if bytes(img[off:off + len(ob)]) != ob or len(ob) != len(nb): sys.exit(f'gen_embed: option {o}: {n}+{off:#x} is not the original the product lists')
        if os.environ.get('DM_TEST_EMBED_NO_OPTIONS'): continue   # negative control of t_gen_embed only: checked, not written
        for off, ob, nb in rows[o]: img[off:off + len(nb)] = nb
        print(f'gen_embed: option {o}: {len(rows[o])} rows written into {n}', file=sys.stderr)
    if os.environ.get('DM_TEST_EMBED_NO_OPTIONS'): return src
    copy = os.path.join(os.path.dirname(os.path.abspath(dst)), f'{n}.embedded.bin'); open(copy, 'wb').write(img)
    return copy
PG = 0x4000
def r16(x): return (x + PG - 1) & ~(PG - 1)
asm = ['// generated by ios/tools/gen_embed.py, do not edit']
flags = []
for n in names:
    hdr = dict(l[2:].split() for l in open(f'{out}/{n}.fixups.tsv'))
    te, po = int(hdr['TEXT_END'], 16), int(hdr['PATCH_OFF'], 16)
    ko, ks = int(hdr['KEY_PAGE_OFF'], 16), int(hdr['KEY_PAGE_SIZE'], 16)
    bin_ = embedded_image(n); sz = os.path.getsize(bin_)
    a, end = r16(te), r16(sz)
    assert po % PG == 0 and a <= ko and ko + ks <= po and ko % PG == 0 and ks == PG
    for sect, lo, hi in ((f'__TEXT,__dm{n}x0', 0, a), (f'__DM{n}W,__img', a, po), (f'__TEXT,__dm{n}x1', po, end)):
        assert all(len(x) <= 16 for x in sect.split(','))
        fill = min(hi, sz) - lo
        asm += [f'    .section {sect}', '    .p2align 14', f'    .incbin "{bin_}", {lo:#x}, {fill:#x}']
        if hi - lo > fill: asm.append(f'    .space {hi - lo - fill:#x}')
        asm.append('    .p2align 14')   # Pad the section end to 16K: vm_remap takes whole pages
    flags.append(f'-Wl,-segprot,__DM{n}W,rw,rw')
missing = [o for o in WANTED if o not in seen]
if missing: sys.exit(f'gen_embed: options {",".join(missing)}: no module of this product lists them')
open(dst, 'w').write('\n'.join(asm) + '\n')
print(' '.join(flags))
